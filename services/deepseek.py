_client: AsyncOpenAI | None = None


def get_client() -> AsyncOpenAI:
    global _client
    if _client is None:
        _client = AsyncOpenAI(
            api_key=os.environ["DEEPSEEK_API_KEY"],
            base_url="https://openrouter.ai/api/v1",
            timeout=30.0,
        )
    return _client


async def chat_with_ai(history: list[dict], user_message: str) -> str:
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    for msg in history:
        messages.append({"role": msg["role"], "content": msg["content"]})
    messages.append({"role": "user", "content": user_message})

    try:
        client = get_client()
        response = await client.chat.completions.create(
            model="deepseek/deepseek-chat",
            messages=messages,
            temperature=0.7,
            max_tokens=800,
        )
        content = response.choices[0].message.content
        return content.strip() if content else "Не удалось получить ответ."
    except (APIError, APITimeoutError, asyncio.TimeoutError) as e:
        logger.error("DeepSeek API error: %s", e)
        return "Извините, сервис временно недоступен, попробуйте позже."
    except Exception as e:
        logger.error("Unexpected error in chat_with_ai: %s", e)
        return "Извините, сервис временно недоступен, попробуйте позже."


async def generate_daily_advice() -> str:
    topic = random.choice(ADVICE_TOPICS)
    messages = [
        {
            "role": "user",
            "content": (
                f"Дай один короткий позитивный психологический совет {topic}. "
                "На русском языке, 1-2 предложения. Только сам совет, без вступлений и заголовков."
            ),
        }
    ]
    try:
        client = get_client()
        response = await client.chat.completions.create(
            model="deepseek/deepseek-chat",
            messages=messages,
            temperature=1.0,
            max_tokens=150,
        )
        content = response.choices[0].message.content
        return content.strip() if content else ""
    except Exception as e:
        logger.error("Error generating daily advice: %s", e)
        return ""


# ──────────────────── разбивка длинных ответов ────────────────────────────

_SENTENCE_END = re.compile(r"(?<=[.!?])\s+")


def split_long_message(text: str, limit: int = 4096) -> list[str]:
    if len(text) <= limit:
        return [text]

    parts: list[str] = []
    current = ""

    for sentence in _SENTENCE_END.split(text):
        sentence = sentence.strip()
        if not sentence:
            continue
        candidate = (current + " " + sentence).strip() if current else sentence
        if len(candidate) <= limit:
            current = candidate
        else:
            if current:
                parts.append(current)
            if len(sentence) > limit:
                for i in range(0, len(sentence), limit):
                    parts.append(sentence[i: i + limit])
                current = ""
            else:
                current = sentence

    if current:
        parts.append(current)

    return parts